#!/usr/bin/env python3
"""Fills in your PUBLIC values: assets/js/config.js and the Content-Security-Policy <meta> in every HTML file. Refuses secret keys.
   python scripts/configure.py --url https://abcd.supabase.co --anon <anon/publishable key> \
          --admin https://your-admin.pages.dev --guest-email you+moments@gmail.com
   Re-run with --bump after editing CSS/JS to refresh the ?v= cache-busting number in every page.
"""
import argparse, base64, datetime, json, re, sys
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument("--url"); ap.add_argument("--anon"); ap.add_argument("--admin"); ap.add_argument("--guest-email", dest="guest")
ap.add_argument("--bump", action="store_true", help="only refresh the ?v= number")
a = ap.parse_args()
root = Path(__file__).resolve().parent.parent
htmls = [p for p in root.rglob("*.html") if "node_modules" not in p.parts and p.name != "google818061acc27c6c5b.html" and not p.name.startswith("google")]

def bump():
    v = datetime.datetime.now().strftime("%Y%m%d%H%M"); n = 0
    for p in htmls:
        t = p.read_text(encoding="utf-8"); t2 = re.sub(r"(\.(?:css|js))\?v=\d+", rf"\1?v={v}", t)
        if t2 != t: p.write_text(t2, encoding="utf-8"); n += 1
    # ES module imports between our own scripts carry the same number, so a visitor never mixes old and new modules.
    m = 0
    for p in (root / "assets" / "js").glob("*.js"):
        t = p.read_text(encoding="utf-8")
        t2 = re.sub(r"""((?:from\s+|import\()\s*["']\./[A-Za-z0-9_-]+\.js)(?:\?v=\d+)?(["'])""", rf"\1?v={v}\2", t)
        if t2 != t: p.write_text(t2, encoding="utf-8"); m += 1
    print(f"cache-busting version {v} written to {n} page(s) and {m} module(s)")

if a.bump and not a.url: bump(); sys.exit(0)
if not (a.url and a.anon and a.admin and a.guest): ap.error("--url, --anon, --admin and --guest-email are required")
supa, admin = a.url.rstrip("/"), a.admin.rstrip("/")
if not re.fullmatch(r"https://[a-z0-9-]+\.supabase\.co", supa): sys.exit("URL must look like https://xxxx.supabase.co")
if not re.fullmatch(r"https://[A-Za-z0-9.-]+", admin): sys.exit("--admin must be an origin like https://name.pages.dev (no path)")
if not re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", a.guest): sys.exit("--guest-email must be an email address")
k = a.anon.strip()
if k.startswith("sb_secret_"): sys.exit("STOP: that is a SECRET key. Use the anon / publishable key.")
if k.count(".") == 2:
    try:
        pl = k.split(".")[1]; role = json.loads(base64.urlsafe_b64decode(pl + "=" * (-len(pl) % 4))).get("role")
        if role == "service_role": sys.exit("STOP: that is the service_role key. Use the anon key. It must never be in a public site.")
    except (ValueError, json.JSONDecodeError): pass

(root / "assets/js/config.js").write_text(f'''// PUBLIC values only (safe to commit). Generated by scripts/configure.py
window.SITE_CONFIG = {{
  SUPABASE_URL: {json.dumps(supa)},
  SUPABASE_ANON_KEY: {json.dumps(k)},
  ADMIN_ORIGIN: {json.dumps(admin)},
  MOMENTS_GUEST_EMAIL: {json.dumps(a.guest)}
}};
''', encoding="utf-8")
csp = ("default-src 'none'; script-src 'self'; style-src 'self' https://fonts.googleapis.com; font-src https://fonts.gstatic.com; "
       f"img-src 'self' data: {supa}; connect-src 'self' {supa}; base-uri 'self'; form-action 'self'; frame-src 'none'; object-src 'none'")
meta = f'<meta http-equiv="Content-Security-Policy" content="{csp}">'
n = 0
for p in htmls:
    t = p.read_text(encoding="utf-8"); t2, c = re.subn(r'<meta http-equiv="Content-Security-Policy"[^>]*>', meta, t)
    if c: p.write_text(t2, encoding="utf-8"); n += 1
print(f"Wrote assets/js/config.js and updated the CSP in {n} HTML file(s). Next: run with --bump when you change code, then commit.")
